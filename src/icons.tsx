const Pixel = ({ rows, size, color }: { rows: string[]; size: number; color: string }) => (
  <svg width={size} height={size} viewBox="0 0 12 12" shapeRendering="crispEdges">
    {rows.flatMap((row, y) => row.split("").map((ch, x) => (
      ch === "#" ? <rect key={`${x}-${y}`} x={x} y={y} width={1.02} height={1.02} fill={color} /> : null
    )))}
  </svg>
);

const lum = (hex: string) => {
  const n = parseInt(hex.replace("#", ""), 16);
  return (0.2126 * ((n >> 16) & 255) + 0.7152 * ((n >> 8) & 255) + 0.0722 * (n & 255)) / 255;
};

export const Icon = ({ name, size, color }: { name: string; size: number; color?: string }) => {
  const col = color ?? T.iconInk;
  if (name.startsWith("brand:")) {
    const slug = name.slice(6).toLowerCase();
    const icon = (SI as any)["si" + slug.charAt(0).toUpperCase() + slug.slice(1)];
    if (!icon) {
      return (
        <div style={{ width: size, height: size, border: `3px dashed ${C.muted}`, borderRadius: 16,
          color: C.muted, display: "flex", alignItems: "center", justifyContent: "center", fontSize: 18 }}>
          {slug}
        </div>
      );
    }
    // very dark brand colours vanish on the dark background -> use white
    const fill = lum(icon.hex) < 0.25 ? (T.light ? "#111111" : "#ffffff") : `#${icon.hex}`;
    return (
      <svg width={size} height={size} viewBox="0 0 24 24">
        <path d={icon.path} fill={fill} />
      </svg>
    );
  }
  const g = GLYPHS[name];
  if (T.iconStyle === "pixel" && PIXEL[name]) return <Pixel rows={PIXEL[name]} size={size} color={col} />;
  if (!g) {
    return (
      <svg width={size} height={size} viewBox="0 0 64 64">
        <rect x="10" y="10" width="44" height="44" rx="8" stroke={col} {...S} />
      </svg>
    );
  }
  if (T.iconStyle === "glow2") {
    // line glyph + offset magenta ghost + glow (neon sign look)
    return (
      <svg width={size} height={size} viewBox="0 0 64 64" style={{ overflow: "visible", filter: `drop-shadow(0 0 5px ${col})` }}>
        <g transform="translate(-2.2 1.6)" opacity={0.55}>{g(C.pink)}</g>
        {g(col)}
      </svg>
    );
  }
  if (T.iconStyle === "duo") {
    // gradient-filled glyph with a light stroke (AI look)
    FILL = "url(#icg)";
    const node = g("#ffffff");
    FILL = "none";
    return (
      <svg width={size} height={size} viewBox="0 0 64 64" style={{ overflow: "visible", filter: `drop-shadow(0 0 7px ${C.go}88)` }}>
        <defs>
          <linearGradient id="icg" x1="0" y1="0" x2="1" y2="1">
            <stop offset="0" stopColor={C.go} />
            <stop offset="1" stopColor={C.blue} />
          </linearGradient>
        </defs>
        {node}
      </svg>
    );
  }
  return (
    <svg width={size} height={size} viewBox="0 0 64 64">{g(col)}</svg>
  );
};
